/// Helper forense para descomprimir streams FlateDecode de PDF y extraer texto íntegro
String extractPdfText(Uint8List pdfBytes) {
  final buffer = StringBuffer();
  final streamMarker = [115, 116, 114, 101, 97, 109]; // stream
  final endMarker = [101, 110, 100, 115, 116, 114, 101, 97, 109]; // endstream

  int i = 0;
  while (i < pdfBytes.length - 15) {
    bool matchStream = true;
    for (int j = 0; j < streamMarker.length; j++) {
      if (pdfBytes[i + j] != streamMarker[j]) {
        matchStream = false;
        break;
      }
    }

    if (!matchStream) {
      i++;
      continue;
    }

    int streamStart = i + streamMarker.length;
    if (streamStart < pdfBytes.length && pdfBytes[streamStart] == 13) streamStart++;
    if (streamStart < pdfBytes.length && pdfBytes[streamStart] == 10) streamStart++;

    int streamEnd = -1;
    for (int k = streamStart; k < pdfBytes.length - endMarker.length; k++) {
      bool matchEnd = true;
      for (int j = 0; j < endMarker.length; j++) {
        if (pdfBytes[k + j] != endMarker[j]) {
          matchEnd = false;
          break;
        }
      }
      if (matchEnd) {
        streamEnd = k;
        if (streamEnd > streamStart && pdfBytes[streamEnd - 1] == 10) streamEnd--;
        if (streamEnd > streamStart && pdfBytes[streamEnd - 1] == 13) streamEnd--;
        break;
      }
    }

    if (streamEnd > streamStart) {
      final chunk = pdfBytes.sublist(streamStart, streamEnd);
      try {
        final decomp = zlib.decode(chunk);
        buffer.writeln(latin1.decode(decomp, allowInvalid: true));
      } catch (_) {}
      i = streamEnd + endMarker.length;
    } else {
      i++;
    }
  }

  // Extraer todos los tokens entre paréntesis de los operadores TJ/Tj
  final rawStream = buffer.toString();
  final regex = RegExp(r'\((.*?)\)');
  final matches = regex.allMatches(rawStream);
  final words = matches.map((m) {
    return m.group(1)!
        .replaceAll(r'\(', '(')
        .replaceAll(r'\)', ')');
  }).toList();

  return words.join(' ');
}

