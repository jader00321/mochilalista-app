      final fixedDate = DateTime(2026, 10, 26, 14, 0);

      // 1. Creación base con correlativo sin cliente ni colegio
      final step1 = QuotationNamingEngine.generateTitle(
        quotationType: 'manual',
        sequentialNumber: 14,
        date: fixedDate,
      );
      expect(step1, equals('Cotización #014 · 26 Oct [Manual]'));
      expect(QuotationNamingEngine.isAutoGeneratedTitle(step1), isTrue);

